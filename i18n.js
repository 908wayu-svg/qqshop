let langMemory = null;    // จำภาษาไว้ในหน้านี้ เผื่อบันทึกลงเครื่องไม่ได้

function getLang() {
  try { return localStorage.getItem(LANG_KEY) || langMemory || "th"; }
  catch { return langMemory || "th"; }
}

function setLang(lang) {
  langMemory = lang;
  try { localStorage.setItem(LANG_KEY, lang); }
  catch { /* จำข้ามหน้าไม่ได้ก็ยังสลับภาษาในหน้านี้ได้ตามปกติ */ }
  applyLang();
  document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
}

function toggleLang() { setLang(getLang() === "th" ? "en" : "th"); }

// t("cart") -> ข้อความตามภาษาปัจจุบัน
function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.th[key] || key;
}

// t() แบบใส่ค่าแทนที่ {ชื่อ} ในข้อความ — ใช้กับข้อความที่มีตัวเลขมาจาก shop-config
// เช่น tv("claim_left", { n: 7 }) -> "เหลือเวลาแจ้งเคลมอีก 7 นาที"
// ทำแบบนี้เพื่อให้ข้อความทั้งประโยคอยู่ในไฟล์แปลไฟล์เดียว ไม่ต้องต่อสตริงในโค้ด
// (ภาษาอังกฤษกับไทยเรียงลำดับคำไม่เหมือนกัน ต่อสตริงเองแล้วประโยคจะเพี้ยน)
function tv(key, vars = {}) {
  return String(t(key)).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// จัดรูปแบบเงินบาท — โชว์ทศนิยมเฉพาะตอนที่มีเศษจริง (ซองอั่งเปาอาจได้ 25.50 บาท)
function money(n) {
  const v = Number(n) || 0;
  const digits = Number.isInteger(v) ? 0 : 2;
  return "฿" + v.toLocaleString(getLang() === "th" ? "th-TH" : "en-US", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}

// แปลทุก element ที่มี data-i18n / data-i18n-placeholder
function applyLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  // คำอธิบายตอนเอาเมาส์ไปชี้ / ที่โปรแกรมอ่านหน้าจอใช้อ่าน (ปุ่มที่มีแต่ไอคอน)
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const s = t(el.dataset.i18nTitle);
    el.title = s;
    el.setAttribute("aria-label", s);
  });
  document.querySelectorAll("[data-lang-label]").forEach(el => { el.textContent = lang === "th" ? "EN" : "ไทย"; });
}

document.addEventListener("DOMContentLoaded", applyLang);
